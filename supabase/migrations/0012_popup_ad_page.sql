- 업로드 파일 형식: JPG, PNG, WEBP 파일을 권장해요. 웹 브라우저가 표시할 수 있는 이미지면 되고, 짭킷이 형식을 따로 제한하지는 않아요. (동영상·PDF는 사용할 수 없어요)
- 최대 파일 용량: 짭킷에서 정해 둔 용량 제한은 없어요. 다만 모바일에서도 빠르게 뜨도록 가볍게 만들어 주세요.

