## 2. 광고 이미지 제작 규격
- 이미지 비율: 4 : 5 (가로 : 세로, 세로로 긴 모양)
- 화면 표시 크기: 가로 최대 약 382px × 세로 약 478px (더 좁은 화면에서는 비율을 유지한 채 줄어들어요)
- 권장 제작 크기: 768 × 960px (표시 크기의 2배 안팎. 고해상도 화면에서도 선명하도록 이 크기 이상을 권장해요)
