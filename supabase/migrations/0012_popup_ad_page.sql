- 왼쪽 위에는 '광고' 표시(최대 40자), 오른쪽 위에는 닫기 버튼이 겹쳐 보여요. 두 모서리에는 중요한 내용을 두지 마세요.
- 이미지 아래쪽에는 어두운 그라데이션과 함께 제목(최대 60자), 설명(최대 300자), 버튼(버튼 글자 최대 20자)이 글자로 올라가요. 이 부분에 중요한 내용이나 같은 문구를 넣으면 가려지거나 겹쳐 보여요.
